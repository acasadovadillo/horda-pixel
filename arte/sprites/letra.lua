-- letra (hoja 366x10, celdas 6x10): tipografía de plantilla en mayúsculas, blanco puro.
-- Cuerpo 5x7 en columnas 0-4, filas 2-8; tildes en las filas 0-1; cola de coma en la fila 9.
-- Las mayúsculas con tilde llevan el cuerpo en 6 filas (3-8) para que la tilde no se pegue.
