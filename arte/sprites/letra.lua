-- Cada glifo: lista de filas empezando en la fila 'y' (por defecto 2) de la celda.
local function g(filas, y) return { filas = filas, y = y or 2 } end
local AG, TI = { "...#.", "..#.." }, { ".##.#", "#..#." }
local function con(acento, cuerpo)        -- tilde en filas 0-1, cuerpo en 3-8
  local f = { acento[1], acento[2], "....." }
  for _, r in ipairs(cuerpo) do f[#f + 1] = r end
  return g(f, 0)
end

